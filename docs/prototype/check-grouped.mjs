import {pathToFileURL} from 'node:url'
import {resolve} from 'node:path'
import {mkdir,writeFile} from 'node:fs/promises'
import assert from 'node:assert/strict'
const {chromium}=await import(pathToFileURL(resolve(process.argv[2],'playwright/index.mjs')).href)
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
const out=resolve('docs/prototype/screenshots-v4');await mkdir(out,{recursive:true})
try{
await page.goto('http://127.0.0.1:3182/')
await page.locator('[data-class="input"]').waitFor()
assert.equal(await page.locator('.context-class').count(),4)
assert.deepEqual(await page.locator('[data-class="input"] [data-entry]').evaluateAll(xs=>xs.map(x=>x.dataset.entry)),['u1','u2'])
assert.deepEqual(await page.locator('[data-class="turn-13"] [data-entry]').evaluateAll(xs=>xs.map(x=>x.dataset.entry)),['a1','t1','t2','a2'])
assert.equal(await page.locator('[data-entry]').count(),8)
await page.screenshot({path:resolve(out,'classified-light.png'),fullPage:true})
await page.locator('[data-entry="t1"]>summary').click()
assert.ok(await page.locator('#entry-t1 pre').isVisible())
await page.screenshot({path:resolve(out,'selected-content.png'),fullPage:true})
await page.locator('#theme').click();await page.screenshot({path:resolve(out,'classified-dark.png'),fullPage:true});await page.locator('#theme').click()
await page.locator('#expandEverything').click()
assert.equal(await page.locator('[data-entry][open]').count(),8)
await page.locator('[data-id="u2"]').click();await page.locator('#edit').click();await page.locator('#draft').fill('先补充回归测试。');await page.locator('#preview').click();await page.locator('#apply').click();await page.locator('#done').click()
assert.equal(await page.locator('#queueCount').innerText(),'1')
await page.locator('#collapseEverything').click();assert.equal(await page.locator('[data-class][open]').count(),0)
await page.locator('#orderedMode').click()
assert.deepEqual(await page.locator('.context-entry').evaluateAll(xs=>xs.map(x=>x.id)),['s0','c1','u1','a1','t1','t2','a2','u2'].map(x=>'entry-'+x))
await page.locator('#groupedMode').click();await page.locator('#search').fill('const key')
assert.equal(await page.locator('[data-entry]').count(),1);assert.match(await page.locator('#coverage').innerText(),/不是完整视图/)
await page.locator('#search').fill('');await page.locator('#expandEverything').click()
await page.setViewportSize({width:390,height:844});await page.screenshot({path:resolve(out,'classified-mobile.png'),fullPage:true})
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));assert.deepEqual(errors,[])
await writeFile(resolve(out,'qa.json'),JSON.stringify({passed:true,scope:'classified simulated prototype',checks:['existing user/system/turn structure','eight unique entries','class internal order','independent collapse','full text and code expansion','ordered mode retains original sequence','code search and scope','edit preview queue','dark/light/mobile'],pageErrors:errors},null,2))
console.log('Classified prototype QA passed')
}finally{await browser.close()}
