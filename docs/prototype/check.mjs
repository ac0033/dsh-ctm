// Browser QA for the standalone simulated prototype, not CTM runtime tests.
import { pathToFileURL } from 'node:url'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import assert from 'node:assert/strict'
const { chromium } = await import(pathToFileURL(resolve(process.argv[2], 'playwright/index.mjs')).href)
const out = resolve('docs/prototype/screenshots')
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto('http://127.0.0.1:3182')
  await page.locator('[data-id="t1"]').waitFor()
  await page.screenshot({ path: resolve(out, 'reading-light.png'), fullPage: true })
  await page.locator('#theme').click()
  assert.equal(await page.locator('body').getAttribute('data-ds-dark-theme'), '')
  await page.screenshot({ path: resolve(out, 'reading-dark.png'), fullPage: true })
  await page.locator('#theme').click()
  await page.locator('#filter').selectOption('tool')
  assert.equal(await page.locator('[data-id]').count(), 2)
  await page.locator('#search').fill('pageSize')
  assert.equal(await page.locator('[data-id]').count(), 2)
  await page.locator('#search').fill('不存在的内容')
  assert.equal(await page.locator('[data-id]').count(), 0)
  await page.locator('#search').fill('')
  await page.locator('#filter').selectOption('all')
  await page.locator('[data-id="u2"]').click()
  await page.locator('#edit').click()
  await page.locator('#draft').fill('请先增加分页大小变化的回归测试，再修改缓存键。')
  await page.locator('#preview').click()
  await page.screenshot({ path: resolve(out, 'edit-preview.png'), fullPage: true })
  await page.locator('#apply').click()
  assert.equal(await page.locator('#queueCount').textContent(), '1')
  await page.locator('[data-turn="11"]').click()
  await page.locator('#diffHistory').click()
  assert.match(await page.locator('#detail').innerText(), /压缩摘要/)
  await page.screenshot({ path: resolve(out, 'history-diff.png'), fullPage: true })
  await page.locator('#back').click()
  await page.locator('#fork').click()
  assert.equal(await page.locator('#forkDialog').evaluate(el => el.open), true)
  await page.locator('#confirmFork').click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('#close').click()
  await page.locator('#mobileTurns').selectOption('live')
  await page.screenshot({ path: resolve(out, 'reading-mobile.png'), fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.deepEqual(errors, [])
  await writeFile(resolve(out, 'qa.json'), JSON.stringify({ passed: true, scope: 'simulated design prototype only', scenarios: ['light/dark', 'source filter', 'search and empty state', 'edit preview and simulated queue', 'historical diff', 'simulated fork dialog', '390px viewport'], pageErrors: errors }, null, 2) + '\n')
  console.log('Prototype browser QA passed; screenshots: ' + out)
} finally { await browser.close() }
