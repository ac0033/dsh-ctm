import { pathToFileURL } from 'node:url'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import assert from 'node:assert/strict'
const { chromium } = await import(pathToFileURL(resolve(process.argv[2], 'playwright/index.mjs')).href)
const out=resolve('docs/prototype/screenshots-v2')
await mkdir(out,{recursive:true})
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',error=>errors.push(error.message))
try {
 await page.goto('http://127.0.0.1:3182')
 await page.locator('[data-group="recent"]').waitFor()
 assert.equal(await page.locator('.group').count(),3)
 assert.equal(await page.locator('.group[open]').count(),0)
 assert.equal(await page.locator('#inspect').isVisible(),false)
 assert.equal(await page.locator('#queue').isVisible(),false)
 await page.screenshot({path:resolve(out,'overview-light.png'),fullPage:true})
 await page.locator('#theme').click()
 await page.screenshot({path:resolve(out,'overview-dark.png'),fullPage:true})
 await page.locator('#theme').click()
 await page.locator('[data-group="recent"] > summary').click()
 await page.locator('[data-id="u2"]').click()
 assert.equal(await page.locator('.technical[open]').count(),0)
 await page.locator('#edit').click()
 await page.locator('#draft').fill('请先补充分页回归测试，再修改缓存键。')
 await page.locator('#preview').click()
 await page.screenshot({path:resolve(out,'edit-preview.png'),fullPage:true})
 await page.locator('#revise').click()
 assert.equal(await page.locator('#draft').inputValue(),'请先补充分页回归测试，再修改缓存键。')
 await page.locator('#preview').click()
 await page.locator('#apply').click()
 assert.equal(await page.locator('#queueCount').textContent(),'1')
 await page.locator('#done').click()
 await page.locator('#changes').click()
 await page.screenshot({path:resolve(out,'changes.png'),fullPage:true})
 await page.locator('#compression').click()
 await page.keyboard.press('Escape')
 await page.locator('#historyPicker > summary').click()
 await page.locator('#historyTurn').selectOption('11')
 await page.locator('#compare').click()
 assert.match(await page.locator('#dialogContent').innerText(),/内容压缩/)
 await page.locator('#close').click()
 await page.locator('#fork').click()
 await page.locator('#confirmFork').click()
 await page.locator('#current').click()
 await page.locator('#toggleAll').click()
 await page.locator('#source').selectOption('tool')
 assert.equal(await page.locator('[data-id]').count(),2)
 await page.locator('#search').fill('不存在的内容')
 assert.equal(await page.locator('[data-id]').count(),0)
 await page.locator('#toggleAll').click()
 await page.locator('#queue').click()
 await page.locator('#clear').click()
 assert.equal(await page.locator('#queue').isVisible(),false)
 await page.reload()
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:resolve(out,'overview-mobile.png'),fullPage:true})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
 assert.deepEqual(errors,[])
 await writeFile(resolve(out,'qa.json'),JSON.stringify({passed:true,scope:'simulated progressive-disclosure prototype',scenarios:['three collapsed groups by default','no initial inspector or empty queue','edit-preview-back preserves draft','queue only appears after confirmation','changes and historical comparison','simulated fork','search and source filter','dark/light','390px no overflow','Escape closes dialog'],pageErrors:errors},null,2)+'\n')
 console.log('Reader v2 browser QA passed')
}finally{await browser.close()}
